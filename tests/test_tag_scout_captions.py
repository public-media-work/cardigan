class TestDecodeSCC:
    def test_pop_on_caption_decodes_to_text(self):
        # RCL, ENM, PAC(row15), "Hello, world.", EOC -- all control codes
        # doubled as a real encoder emits them.
        scc = (
            "Scenarist_SCC V1.0\n\n"
            "00:00:01;00\t9420 9420 94ae 94ae 9470 9470 "
            "c8e5 ecec ef2c 20f7 ef72 ec64 2e80 942f 942f\n"
        )
        caps = cts.decode_scc(scc)
        assert [c.text for c in caps] == ["Hello, world."]

    def test_parity_bits_are_stripped(self):
        # 0xc8 -> 'H' only if the high parity bit is masked off.
        scc = "Scenarist_SCC V1.0\n\n00:00:01;00\t9420 9420 9470 9470 c8e9 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "Hi"

    def test_doubled_control_codes_do_not_duplicate_text(self):
        scc = "Scenarist_SCC V1.0\n\n" "00:00:01;00\t9420 9420 9470 9470 c1c2 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "AB"

    def test_null_padding_is_ignored(self):
        # 0x80 masks to 0x00 -- filler, not a character.
        scc = "Scenarist_SCC V1.0\n\n00:00:01;00\t9420 9420 9470 9470 c180 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "A"

    def test_basic_set_nonascii_codepoints(self):
        # 0x7D is N-tilde in the 608 basic set, not '}'.
        scc = "Scenarist_SCC V1.0\n\n00:00:01;00\t9420 9420 9470 9470 fdfe 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "Ññ"

    def test_special_north_american_char(self):
        # 0x11 0x37 -> music note.
        scc = "Scenarist_SCC V1.0\n\n00:00:01;00\t9420 9420 9470 9470 91b7 91b7 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "♪"

    def test_extended_char_replaces_preceding_fallback(self):
        # Encoder sends 'U' then the extended code for U-umlaut; the decoder
        # must drop the fallback rather than emit both.
        scc = "Scenarist_SCC V1.0\n\n00:00:01;00\t9420 9420 9470 9470 2055 9224 9224 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "Ü"

    def test_channel_two_control_codes_are_ignored(self):
        # 0x1F-range pairs are CC2; we only decode CC1.
        scc = "Scenarist_SCC V1.0\n\n" "00:00:01;00\t9420 9420 9470 9470 c1c2 1f20 1f20 942f 942f\n"
        assert cts.decode_scc(scc)[0].text == "AB"

    def test_roll_up_flushes_on_carriage_return(self):
        # RU2, PAC, "one", CR, "two", CR
        scc = (
            "Scenarist_SCC V1.0\n\n"
            "00:00:01;00\t9425 9425 9470 9470 ef6e e520 94ad 94ad\n"
            "00:00:03;00\t74f7 ef20 94ad 94ad\n"
        )
        assert [c.text for c in cts.decode_scc(scc)] == ["one", "two"]

    def test_start_timecode_is_captured(self):
        scc = "Scenarist_SCC V1.0\n\n00:00:10;00\t9420 9420 9470 9470 c1 942f 942f\n"
        caps = cts.decode_scc(scc)
        assert caps[0].start_ms == pytest.approx(10_000, abs=50)

    def test_empty_file_yields_no_captions(self):
        assert cts.decode_scc("Scenarist_SCC V1.0\n\n") == []


