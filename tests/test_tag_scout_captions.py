class TestParseSRT:
    def test_basic_cues(self):
        srt = "1\n00:00:01,000 --> 00:00:03,000\nHello there\n\n2\n00:00:04,000 --> 00:00:06,000\nSecond cue\n"
        caps = cts.parse_srt(srt)
        assert [c.text for c in caps] == ["Hello there", "Second cue"]
        assert caps[0].start_ms == 1000

    def test_multiline_cue_joins_with_space(self):
        srt = "1\n00:00:01,000 --> 00:00:03,000\nfirst line\nsecond line\n"
        assert cts.parse_srt(srt)[0].text == "first line second line"

    def test_malformed_block_is_skipped_not_fatal(self):
        srt = "1\nnot a timecode\nnonsense\n\n2\n00:00:04,000 --> 00:00:06,000\nGood cue\n"
        assert [c.text for c in cts.parse_srt(srt)] == ["Good cue"]


# ---------------------------------------------------------------------------
# Rolling-window de-duplication
#
# The real prize. Live-captioned SRTs repeat the whole visible 2-3 line
# window in every cue, so naive extraction inflates every term's frequency
# 2-3x and skews keyword ranking toward whatever happened to sit mid-window.
# ---------------------------------------------------------------------------


class TestRollingWindowMerge:
    def test_overlapping_window_collapses(self):
        caps = [
            cts.Caption(0, ">> The governor spoke today"),
            cts.Caption(2000, ">> The governor spoke today about the state budget"),
            cts.Caption(4000, "about the state budget and the shortfall ahead"),
        ]
        assert cts.merge_captions(caps) == (
            ">> The governor spoke today about the state budget and the shortfall ahead"
        )

    def test_non_overlapping_cues_are_all_kept(self):
        caps = [cts.Caption(0, "Hello there"), cts.Caption(2000, "Something else entirely")]
        assert cts.merge_captions(caps) == "Hello there Something else entirely"

    def test_exact_repeat_collapses_to_one(self):
        caps = [cts.Caption(0, "same words"), cts.Caption(2000, "same words")]
        assert cts.merge_captions(caps) == "same words"

    def test_overlap_matches_on_word_boundaries_only(self):
        # "budge" must not be treated as an overlap with "budget".
        caps = [cts.Caption(0, "the budge"), cts.Caption(2000, "budget hearing")]
        assert cts.merge_captions(caps) == "the budge budget hearing"

    def test_partial_word_repetition_within_window(self):
        caps = [
            cts.Caption(0, "line one\nline two"),
            cts.Caption(2000, "line two\nline three"),
        ]
        assert cts.merge_captions(caps) == "line one line two line three"


