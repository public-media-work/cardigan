class TestExtract:
    def test_srt_end_to_end(self):
        srt = "1\n00:00:01,000 --> 00:01:03,000\nWisconsin dairy farms\n"
        result = cts.extract(srt)
        assert result.format == "srt"
        assert "Wisconsin dairy farms" in result.text
        assert result.duration_ms == 63_000
        assert result.cue_count == 1

    def test_live_captioning_is_flagged(self):
        # analyst.md keys speaker-change '>>' as the live-caption tell; the
        # skill needs that signal to suppress name-guessing.
        srt = "1\n00:00:01,000 --> 00:00:03,000\n>> Welcome back\n\n2\n00:00:04,000 --> 00:00:06,000\n>> Thanks for having me\n"
        assert cts.extract(srt).live_captioning is True

    def test_post_production_captions_not_flagged(self):
        srt = "1\n00:00:01,000 --> 00:00:03,000\nWelcome back to the show\n"
        assert cts.extract(srt).live_captioning is False

    def test_scc_end_to_end(self):
        scc = "Scenarist_SCC V1.0\n\n" "00:00:01;00\t9420 9420 9470 9470 c8e5 ecec ef2c 20f7 ef72 ec64 2e80 942f 942f\n"
        result = cts.extract(scc)
        assert result.format == "scc"
        assert result.text == "Hello, world."
