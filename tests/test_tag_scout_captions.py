"""Tests for the tag-scout skill's caption text extractor.

The extractor is the only part of the skill with real logic: everything else
is prompt text. It lives under .claude/skills/ rather than api/, so it is
loaded here by path.

The SCC fixtures below are hand-encoded EIA-608 byte pairs, not round-tripped
through our own encoder -- a fixture generated by the code under test would
prove nothing.
"""

import importlib.util
import sys
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[1] / ".claude" / "skills" / "tag-scout" / "scripts" / "captions_to_text.py"


def _load_module():
    spec = importlib.util.spec_from_file_location("captions_to_text", _SCRIPT)
    module = importlib.util.module_from_spec(spec)
    # @dataclass resolves annotations via sys.modules[cls.__module__], so the
    # module must be registered before exec_module, not after.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


cts = _load_module()


# ---------------------------------------------------------------------------
# Format detection
# ---------------------------------------------------------------------------


class TestDetectFormat:
    def test_scenarist_header_is_scc(self):
        assert cts.detect_format("Scenarist_SCC V1.0\n\n00:00:01;00\t9420 9420\n") == "scc"

    def test_srt_cue_is_srt(self):
        assert cts.detect_format("1\n00:00:01,000 --> 00:00:03,000\nHello\n") == "srt"

    def test_headerless_scc_detected_by_semicolon_timecode_and_hex(self):
        # Some tools drop the Scenarist header. The drop-frame ';' separator
        # plus tab-delimited hex is still unambiguous.
        assert cts.detect_format("00:00:01;00\t9420 9420 c8e5 ecec\n") == "scc"

    def test_unrecognized_content_raises(self):
        with pytest.raises(ValueError):
            cts.detect_format("just some prose that is neither format")


